#!/usr/bin/env python3
"""Generate the evaluation course config/parcours_<h>cm.world (fixed seed, reproducible).

Usage: make_course.py [step_height_m=0.10] [seed=7]
Profile (robot walks towards -x):
  ascent     : risers at x = -2.0, -2.3, -2.6 (h, 2h, 3h)
  landing    : x from -2.9 to -3.9, height 3h
  descent    : risers at x = -3.9, -4.2, -4.5 (2h, h, 0)
  rough      : x from -5.0 to -8.0, |y| < 0.8 m (random tiles, then bumps)
"""
import os
import random
import sys

H = float(sys.argv[1]) if len(sys.argv) > 1 else 0.10
SEED = int(sys.argv[2]) if len(sys.argv) > 2 else 7
TREAD = 0.30
WIDTH = 2.0
random.seed(SEED)


def box(name, x, y, sx, sy, sz, shade):
    return f'''    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {sz / 2:.4f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.4f}</size></box></geometry></collision>
        <visual name="visual"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.4f}</size></box></geometry>
          <material><ambient>{shade:.2f} {shade:.2f} {shade + 0.05:.2f} 1</ambient><diffuse>{shade:.2f} {shade:.2f} {shade + 0.05:.2f} 1</diffuse></material></visual>
      </link>
    </model>
'''


def bump(name, x, y, radius, height):
    # Buried sphere: cap of the given height above the ground.
    zc = height - radius
    return f'''    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {zc:.4f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><sphere><radius>{radius:.3f}</radius></sphere></geometry></collision>
        <visual name="visual"><geometry><sphere><radius>{radius:.3f}</radius></sphere></geometry>
          <material><ambient>0.45 0.5 0.45 1</ambient><diffuse>0.45 0.5 0.45 1</diffuse></material></visual>
      </link>
    </model>
'''


parts = []
# Ascent: step i, top at (i+1) h
for i in range(3):
    parts.append(box(f'up_{i + 1}', -2.0 - TREAD * (i + 0.5), 0.0, TREAD, WIDTH, H * (i + 1), 0.6 + 0.05 * i))
# Upper landing
parts.append(box('landing', -3.4, 0.0, 1.0, WIDTH, 3 * H, 0.8))
# Descent
for i, level in enumerate((2, 1)):
    parts.append(box(f'down_{i + 1}', -3.9 - TREAD * (i + 0.5), 0.0, TREAD, WIDTH, H * level, 0.7 - 0.05 * i))
# Rough ground: 0.2 m tiles of 0-4 cm, then bumps
TILE = 0.20
nx, ny = 8, 8
for ix in range(nx):
    for iy in range(ny):
        hz = random.uniform(0.0, 0.04)
        if hz < 0.005:
            continue
        parts.append(box(f'tile_{ix}_{iy}', -5.0 - TILE * (ix + 0.5), -0.8 + TILE * (iy + 0.5), TILE, TILE, hz,
                         0.5 + 6 * hz))
for k in range(12):
    parts.append(bump(f'bump_{k}', random.uniform(-6.7, -7.9), random.uniform(-0.6, 0.6),
                      random.uniform(0.15, 0.30), random.uniform(0.03, 0.06)))

world = f'''<?xml version="1.0" ?>
<!-- Generated by scripts/make_course.py (step {H * 100:g} cm, seed {SEED}). The robot walks towards -x. -->
<sdf version="1.5">
  <world name="default">
    <include><uri>model://sun</uri></include>
    <include><uri>model://ground_plane</uri></include>
{''.join(parts)}  </world>
</sdf>
'''
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'config',
                   f'parcours_{("%g" % (H * 100)).replace(".", "_")}cm.world')
open(out, 'w').write(world)
print(os.path.normpath(out))
